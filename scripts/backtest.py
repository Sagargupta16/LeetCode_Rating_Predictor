"""Backtest the served model on recent, real LeetCode contests.

For each sampled user this fetches the full contest history, then replays their
most recent rated contests one at a time: the features are rebuilt from the
history *as it stood before that contest*, using the same functions the API
calls (``app/services/features.py``), and the prediction is compared with the
rating change LeetCode actually applied.

Users are sampled from the part of ``data/usernames.json`` that
``scripts/update_data.py`` never fetches (everything past its default slice), so
no backtested contest can be in the training data.

Usage:
    python scripts/backtest.py                       # 50 users, last 5 contests
    python scripts/backtest.py --users 100 --seed 3
    python scripts/backtest.py --output docs/backtest.md
"""

from __future__ import annotations

import argparse
import json
import math
import random
import statistics
import sys
import time
from datetime import UTC, datetime, timedelta
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from app.model_loader import load_model, load_scaler  # noqa: E402
from app.services.features import (  # noqa: E402
    DEFAULT_RATING,
    build_features,
    summarize_history,
)
from scripts.update_data import (  # noqa: E402
    DEFAULT_MAX_USERS,
    build_session,
    fetch_user_contest_history,
)

HISTORY_QUERY = """
query userContestRankingInfo($username: String!) {
    userContestRankingHistory(username: $username) {
        attended
        rating
        ranking
        problemsSolved
        totalProblems
        finishTimeInSeconds
        contest {
            titleSlug
            startTime
        }
    }
}
"""


def replay_user(history, last, since_ts, model, scaler):
    """Yield (slug, predicted, actual) for the user's recent rated contests."""
    rated = [
        i
        for i, h in enumerate(history)
        if h.get("attended") and h.get("rating") is not None and h.get("ranking")
    ]
    for pos, j in enumerate(rated):
        if pos < len(rated) - last:
            continue
        entry = history[j]
        if (entry.get("contest") or {}).get("startTime", 0) < since_ts:
            continue

        before = history[:j]
        prior = [h for h in before if h.get("attended") and h.get("rating")]
        rating = prior[-1]["rating"] if prior else DEFAULT_RATING
        user = summarize_history(before)
        features = build_features(user, rating, entry["ranking"], user["contestIndex"])
        predicted = float(model.predict(scaler.transform(features))[0][0])
        yield entry["contest"]["titleSlug"], predicted, entry["rating"] - rating


def summarize(errors, actuals, predictions):
    abs_err = [abs(e) for e in errors]
    same_sign = sum(
        1 for p, a in zip(predictions, actuals, strict=True) if (p >= 0) == (a >= 0)
    )
    return {
        "contests": len(errors),
        "mae": round(statistics.fmean(abs_err), 2),
        "rmse": round(math.sqrt(statistics.fmean(e * e for e in errors)), 2),
        "median_ae": round(statistics.median(abs_err), 2),
        "within_10": round(100 * sum(e <= 10 for e in abs_err) / len(errors), 1),
        "direction": round(100 * same_sign / len(errors), 1),
        "zero_baseline_mae": round(statistics.fmean(abs(a) for a in actuals), 2),
    }


def render_markdown(report):
    m = report["metrics"]
    p = report["params"]
    return f"""# Backtest

Generated by `python scripts/backtest.py` on {report["date"]}. Each prediction
uses only the history a user had before that contest, built by the same feature
code the API serves, and is compared with the rating change LeetCode applied.

| Metric | Value |
|---|---|
| Contests scored | {m["contests"]} |
| Users | {report["users"]} |
| MAE | **{m["mae"]}** |
| RMSE | {m["rmse"]} |
| Median absolute error | {m["median_ae"]} |
| Predictions within 10 points | {m["within_10"]}% |
| Direction right (gain vs loss) | {m["direction"]}% |
| MAE of always predicting 0 | {m["zero_baseline_mae"]} |

Users were sampled with seed {p["seed"]} from `data/usernames.json` past index
{p["pool_start"]}, the slice `scripts/update_data.py` never fetches, so none of
these contests is in the training data. Up to the last {p["last"]} rated contests
per user count, if they started within {p["since_days"]} days of the run.
{report["skipped"]} sampled accounts had no contest in that window.
Model: `{p["weights"]}`.
"""


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--users", type=int, default=50, help="users to score")
    parser.add_argument("--last", type=int, default=5, help="contests per user")
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument(
        "--since-days",
        type=int,
        default=365,
        help="only score contests that started within this many days",
    )
    parser.add_argument(
        "--pool-start",
        type=int,
        default=DEFAULT_MAX_USERS,
        help="sample usernames from this index on (default: past the training slice)",
    )
    parser.add_argument("--weights", default="models/weights.npz")
    parser.add_argument("--scaler", default="models/scaler.json")
    parser.add_argument("--output", help="write the markdown report here")
    parser.add_argument("--json", help="write the raw report as JSON here")
    parser.add_argument(
        "--delay", type=float, default=0.3, help="seconds between users"
    )
    parser.add_argument(
        "--histories",
        help=(
            "JSON cache of fetched histories: read if it exists, written after "
            "the run, so two models can be compared on identical data"
        ),
    )
    return parser.parse_args()


def load_histories(path):
    if path and path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    return {}


def score_pool(pool, args, model, scaler, since_ts, cached):
    """Replay users from the shuffled pool until ``args.users`` have scored."""
    session = build_session()
    errors, actuals, predictions = [], [], []
    tally = {"users": 0, "skipped": 0, "failed": 0}
    for username in pool:
        if tally["users"] >= args.users:
            break
        history = cached.get(username)
        if history is None:
            history = fetch_user_contest_history(session, username, HISTORY_QUERY)
            time.sleep(args.delay)
        if history is None:
            tally["failed"] += 1
            continue
        cached[username] = history
        rows = list(replay_user(history, args.last, since_ts, model, scaler))
        if not rows:
            tally["skipped"] += 1
            continue
        tally["users"] += 1
        for _, predicted, actual in rows:
            errors.append(predicted - actual)
            actuals.append(actual)
            predictions.append(predicted)
        print(f"[{tally['users']}/{args.users}] {username}: {len(rows)} contests")
    return errors, actuals, predictions, tally


def main() -> int:
    args = parse_args()
    model = load_model(REPO_ROOT / args.weights)
    scaler = load_scaler(REPO_ROOT / args.scaler)

    usernames = json.loads((REPO_ROOT / "data" / "usernames.json").read_text())
    pool = usernames[args.pool_start :]
    random.Random(args.seed).shuffle(pool)  # noqa: S311 - sampling, not crypto

    now = datetime.now(UTC)
    since_ts = int((now - timedelta(days=args.since_days)).timestamp())
    cache_path = Path(args.histories) if args.histories else None
    cached = load_histories(cache_path)

    errors, actuals, predictions, tally = score_pool(
        pool, args, model, scaler, since_ts, cached
    )
    if cache_path:
        cache_path.write_text(json.dumps(cached), encoding="utf-8")

    if not errors:
        print("No contests scored; LeetCode may be throttling.", file=sys.stderr)
        return 1
    if tally["failed"] > tally["users"]:
        print(f"{tally['failed']} fetches failed; refusing to report.", file=sys.stderr)
        return 1

    report = {
        "date": now.strftime("%Y-%m-%d"),
        **tally,
        "params": {
            "seed": args.seed,
            "last": args.last,
            "since_days": args.since_days,
            "pool_start": args.pool_start,
            "weights": args.weights,
        },
        "metrics": summarize(errors, actuals, predictions),
    }
    print(json.dumps(report, indent=2))
    if args.output:
        Path(args.output).write_text(render_markdown(report), encoding="utf-8")
    if args.json:
        Path(args.json).write_text(json.dumps(report, indent=2) + "\n", "utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
